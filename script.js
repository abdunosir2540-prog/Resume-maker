function renderPreview() {
  const t = i18n[state.lang];
  const fullName = [state.firstName, state.lastName].filter(Boolean).join(" ") || t.defaultName;

  document.getElementById("pName").textContent = fullName;
  document.getElementById("pRole").textContent = state.jobTitle || "";

  const contacts = [state.location, state.phone, state.email, state.website].filter(Boolean);
  const pContacts = document.getElementById("pContacts");
  pContacts.innerHTML = "";
  contacts.forEach(item => {
    const div = document.createElement("div");
    div.textContent = item;
    pContacts.appendChild(div);
  });

  const secSummary = document.getElementById("secSummary");
  secSummary.style.display = state.summary.trim() ? "block" : "none";
  document.getElementById("pSummary").textContent = state.summary;

  const validExp = state.experiences.filter(e => e.role || e.company || e.desc);
  document.getElementById("secExperience").style.display = validExp.length ? "block" : "none";
  const pExp = document.getElementById("pExperience");
  pExp.innerHTML = "";
  validExp.forEach(e => {
    const entry = document.createElement("div");
    entry.className = "cv-entry";

    const head = document.createElement("div");
    head.className = "cv-entry-head";

    const title = document.createElement("div");
    title.className = "cv-entry-title";
    title.textContent = e.role || "";

    const date = document.createElement("div");
    date.className = "cv-entry-date";
    date.textContent = e.date || "";

    head.append(title, date);
    entry.appendChild(head);

    if (e.company) {
      const sub = document.createElement("div");
      sub.className = "cv-entry-sub";
      sub.textContent = e.company;
      entry.appendChild(sub);
    }

    if (e.desc) {
      const desc = document.createElement("div");
      desc.className = "cv-entry-desc";
      desc.textContent = e.desc;
      entry.appendChild(desc);
    }

    pExp.appendChild(entry);
  });

  const validEdu = state.educations.filter(e => e.degree || e.school);
  document.getElementById("secEducation").style.display = validEdu.length ? "block" : "none";
  const pEdu = document.getElementById("pEducation");
  pEdu.innerHTML = "";
  validEdu.forEach(e => {
    const entry = document.createElement("div");
    entry.className = "cv-entry";

    const head = document.createElement("div");
    head.className = "cv-entry-head";

    const title = document.createElement("div");
    title.className = "cv-entry-title";
    title.textContent = e.degree || "";

    const date = document.createElement("div");
    date.className = "cv-entry-date";
    date.textContent = e.date || "";

    head.append(title, date);
    entry.appendChild(head);

    if (e.school) {
      const sub = document.createElement("div");
      sub.className = "cv-entry-sub";
      sub.textContent = e.school;
      entry.appendChild(sub);
    }

    pEdu.appendChild(entry);
  });

  const skillsArr = state.skills.split(",").map(s => s.trim()).filter(Boolean);
  document.getElementById("secSkills").style.display = skillsArr.length ? "block" : "none";
  const pSkills = document.getElementById("pSkills");
  pSkills.innerHTML = "";
  skillsArr.forEach(s => {
    const tag = document.createElement("span");
    tag.className = "cv-tag";
    tag.textContent = s;
    pSkills.appendChild(tag);
  });

  const langsArr = state.languages.split(",").map(s => s.trim()).filter(Boolean);
  document.getElementById("secLanguages").style.display = langsArr.length ? "block" : "none";
  const pLangs = document.getElementById("pLanguages");
  pLangs.innerHTML = "";
  langsArr.forEach(l => {
    const tag = document.createElement("span");
    tag.className = "cv-tag";
    tag.textContent = l;
    pLangs.appendChild(tag);
  });
}

